import redline as R


def _scan(text: str):
    return R.scan({"turns": [{"t": 0.0, "role": "agent", "text": text}]})


def _check(cases, name):
    ok, bad = 0, []
    for text, should in cases:
        r = _scan(text)
        if r.blocked == should:
            ok += 1
        else:
            bad.append((text, should, [h.matched for h in r.all_hits]))
    print(f"{name}：{ok}/{len(cases)} 正确")
    for text, should, hits in bad:
        tag = "漏检" if should else "误判"
        print(f"  [{tag}] {text}")
        if hits:
            print(f"        命中：{hits}")
    return ok, len(cases)


