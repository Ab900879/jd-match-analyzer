"""红线引擎回归测试。

结构说明：
  第 0 组  核心回归 —— 每次改规则都必须先过这一组
  第 1 组  同义改写召回 —— 专测"换个说法就绕过词表"的那类句子
  第 2 组  正常话术误判 —— 一条都不许抓，这组挂了就是产品不可用
  第 3 组起  分批验收 —— 每批都是当时新写的、写时未参与调参，数字照实记录在 README 里

为什么分这么多批：**被调过的批次就不再是盲测**。
只有每批第一次跑出来的数字能进 README，后面修完了再跑只能说明"没退化"，不能说"准确率提高了"。
"""
