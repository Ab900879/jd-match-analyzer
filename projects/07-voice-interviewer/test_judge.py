def run() -> int:
    qs = {q["id"]: q for q in core.load_questions()}
    fails = []
    for qid, answer, should, note in CASES:
        q = qs.get(qid)
        if not q:
            fails.append((qid, answer, should, f"题库里没有 {qid}", []))
            continue
        v = core.judge(answer, q)
        if v.passed != should:
            fails.append((qid, answer, should, note, v.failed_rules))

    total = len(CASES)
    pos = sum(1 for _, _, s, _ in CASES if s)
    print(f"用例 {total} 条（好答案 {pos} / 烂答案 {total-pos}），失败 {len(fails)} 条")
    for qid, answer, should, note, rules in fails:
        kind = "误杀好答案" if should else "放过烂答案"
        print(f"  [{kind}] {qid}｜{note}")
        print(f"        回答：{answer[:45]}…")
        print(f"        触发规则：{rules}")
    if not fails:
        print("全部通过。")
    return 0 if not fails else 1


if __name__ == "__main__":
    sys.exit(run())
