# ---- 索要敏感信息：要的动作 + 敏感情报的载体 ----
_ASK_VERB = r"(?:念|说|报|读|发|填|输|给|告诉|提供|核|确认|验证)"
# "扫" 被拿掉了：要"码/卡号/身份证号"这类**信息载体**才算索取敏感信息，
# 而"扫码"是扫码这个动作本身，不产生信息——"您扫这个码可以查许可证"是合规的。
# 扫码类违规（扫码付款/扫码转账）在 private_deal 结构规则里单独判，那边看的是资金动作。
# 这条是第三批验收抓出来的：把"扫"当成索要动作，一句正常的自查话术就变成了违规。
_ASK_TARGET = (
    r"(?:码|数字|卡号|卡|账号|密码|证件|身份证|验证码|短信|背面的|有效期|CVV)"
)
_ASK_PATTERN = re.compile(
    rf"{_ASK_VERB}[^，。！？,.!?]{{0,10}}?{_ASK_TARGET}"
    rf"|{_ASK_TARGET}[^，。！？,.!?]{{0,10}}?{_ASK_VERB}"
)

# ---- 承诺收益：确定性表述 ----
_CERTAIN_PATTERN = re.compile(
    r"(?:固定|写死|锁死|写进|保底|稳的|稳赚|不亏|不会亏|一分不少|不少一分|"
    r"跑不了|跑不掉|跌不了|亏不了|赔不了|拿得回|拿回来|"
    r"每年[^，。！？,.!?]{0,4}(?:个点|个百分|%)|年化[^，。！？,.!?]{0,4}个点)"
)

# ---- 威胁施压：条件 + 后果 ----
# 后果词分三类：
#   ① 征信/法律类后果（征信、档案、起诉、法务、冻结、黑名单）
#   ② 上门类（上门、来人、找上门）
#   ③ 地域型施压（寄到/发到/送到 + 老家/户籍地/村委会/单位/居委会）
# 第 ③ 类是第一版漏掉的：它不含"征信""起诉"这类硬词，但语义上是
# "我知道你住哪、我能寄到你家"——这是典型的心理施压，比明说要起诉更阴。
# 判据不是"寄到"这个动词（寄合同、寄材料都是正常流程），而是
# **寄到 + 与本人当场无关的地域/组织**（老家、户籍地、村委会、单位）。
_THREAT_PATTERN = re.compile(
    # ① 条件式：不 XX 就 XX
    r"(?:不还|不交|不办|不配合|不签|不处理|不理|拖着|不接)"
    r"[^，。！？,.!?]{0,8}?(?:就|的话|会)"
    r"[^，。！？,.!?]{0,14}?(?:征信|记录|档案|起诉|法务|上门|单位|家里|影响|冻结|黑名单"
    r"|来人|找上门|函|传票|派出所|村委|居委|公示|人过去|人过去找|安排人|报公安|报警|报案|经侦|公安)"
    r"|(?:征信|档案|黑名单)[^，。！？,.!?]{0,8}?(?:就有|会留|会有|留下)"
    # ③ 上门类：不等条件句。"法务明天就上门""安排人上门"直接就是施压。
    #    但不含"上门拜访/上门送合同/上门服务"——那些是正常业务，判据落在
    #    上门前面有没有"法务/催收/安排人/就"这类施压语境。
    r"|(?:法务|律师|催收|外访|安排人|派人|人就|直接|明天就|今天就|下午就|马上"
    r"|我们就|就会|就要|会来)[^，。！？,.!?]{0,8}?上门"
    r"|上门(?:找你|找您|催|要钱|要账|收钱|核实|走访|清收)"
    # ② 已发生的法律动作："已经交给法务了""律师函今天寄出"
    #    这类话不说"如果您不还"，直接把后果摆在桌面上，是更硬的一种施压。
    r"|(?:已经|已|就|马上|直接)?[^，。！？,.!?]{0,3}?(?:交给|移交|转到|报送|递到|报)"
    r"[^，。！？,.!?]{0,4}?(?:法务|律师|法院|公安|经侦|催收)"
    r"|(?:律师函|催收函|起诉书|传票)[^，。！？,.!?]{0,4}?(?:今天|明天|已经|已|将|会)?[^，。！？,.!?]{0,4}?"
    r"(?:寄出|发出|送达|提交|立案|寄出去|发出去|送到|送过来|寄过来)"
    # "走诉讼流程/走法律程序/直接起诉"—— 不写"不还就"，也是把后果摆上桌
    r"|(?:走|启动|进入|申请)[^，。！？,.!?]{0,4}?(?:诉讼|法律程序|司法程序|仲裁|强制执行)"
    r"|(?:起诉|诉到|告到)[^，。！？,.!?]{0,4}?(?:法院|法庭)"
    # 地域型施压：寄/发/送/递 + 到 + （可选"您/你/他"）+ 最多 2 字 + 地域/组织指代
    #   抓："寄到您老家那边""寄到你户籍地去""寄到村委会"
    #   放："寄到您单位""寄到您公司"（对本人寄送正常流程）"寄到您手上的地址""发到您邮箱"
    r"|(?:寄|发|送|递)(?:到|去|往)"
    # 先排除"寄到本人手上/手机/邮箱/地址"以及"寄到您单位/公司"——对本人寄送是正常流程。
    r"(?!(?:您|你)?[^，。！？,.!?]{0,4}?(?:手上|手里|手机|邮箱|地址|联系人|本人))"
    r"(?!您[^，。！？,.!?]{0,1}?(?:单位|公司|学校))"
    # "寄到公司前台/公司地址"里的"公司"是自己的公司，不是寄到对方单位施压。
    r"(?!(?:公司|单位)[^，。！？,.!?]{0,2}?(?:前台|地址|总部|门口|收发室|行政))"
    r"(?:您|你|他|她|它)?[^，。！？,.!?]{0,2}?"
    r"(?:老家|户籍地|户口所在地|村里|村委会|居委会|街道办|单位|公司|学校)"
)

# ---- 隔离家人：电诈最关键的一步 ----
# 判据不是"家里"这个词（"寄到您家里""跟家里人商量"都正常），
# 而是 **劝阻性动词 + 沟通动词 + 家人称谓** 三者同现，或者"自己定/自己做主"这种劝独断。
# 家人称谓要收全：爱人、配偶、孩子、先生、太太……漏一个就是一条漏检路径。
# 家人称谓。加"您先生/您太太/您爱人"这种带敬称的写法之前，
# "您先别告诉您先生"漏检了——"先别告诉"命中了，但称谓不在表里，
# 结构规则没抓到，只靠词表的话连"告诉"的对象都不需要，容易漏。
_FAMILY = (r"(?:家里|家人|家里人|父母|爸妈|老人|老婆|老公|爱人|配偶|媳妇|丈夫|妻子"
           r"|孩子|儿子|女儿|闺女|亲戚|朋友|同事|先生|太太|对象|另一半|老伴|老头子|老太太|儿女|子女"
           r"|他|她|他们|她们)")
_ISOLATE_PATTERN = re.compile(
    # 排除"要不要/该不该/会不会"这类里被误吃的"不要"（那个"不要"是疑问的一部分，
    # 后面跟"先跟家里人商量"其实是**鼓励**客户去商量，跟隔离正好相反）。
    # 用分组代替后顾：(?:^|[^要该会需得了想]) 放在同一位置即可。
    rf"(?:^|[^要该会需得了想])(?:别|不要|不用|先别|暂时别|不必|没必要|甭)"
    # ① 直接说给谁听："别跟家里商量" / "先别告诉您先生" / "别让他们知道"
    rf"[^，。！？,.!?]{{0,3}}"
    rf"(?:让|跟|告诉|和|同|对|通知|联系)?[^，。！？,.!?]{{0,2}}"
    rf"{_FAMILY}[^，。！？,.!?]{{0,2}}(?:知道|说|商量|讲|提|透露)"
    # ② 隔着宾语说："先别告诉您先生" —— "告诉"后面才是人称代词，上面那支会把它当宾语跳过，
    #    所以单独列一支：劝阻词 + 告诉类动词 + 任意 4 字内 + 称谓代词 + 动作
    rf"|(?:别|不要|不用|先别|暂时别|不必|没必要|甭)[^，。！？,.!?]{{0,4}}"
    rf"(?:告诉|通知|说给|讲给|提)[^，。！？,.!?]{{0,4}}"
    rf"(?:您|你)?(?:先生|太太|爱人|配偶|老公|老婆|父母|爸妈|家人|家里|他|她)"
    rf"(?:知道|说|听|提)?"
    rf"|{_FAMILY}[^，。！？,.!?]{{0,4}}(?:不知道|别知道)"
    # 劝独断：把决策权从"家庭"收到"个人"，本质是隔离的软版本
    rf"|(?:您|你)(?:自己|自个儿|一个人)(?:就能|可以|直接)?(?:定|决定|做主|拍板)"
    # 保密要求："别外传""别说出去""这事就咱俩知道" —— 隔离的另一种说法，
    # 对象不是家人而是所有人，效果一样：切断外部意见。
    r"|(?:别|不要|不用|先别|切勿|不能)(?:外传|对外说|说出去|往外说|跟别人说|告诉别人|声张|对外讲)"
    # "自己拿主意"和"自己定"是同一类劝独断，前面可能带"您自己/这种事您自己"
    r"|(?:您|你)?(?:自己|自个儿)(?:拿主意|看着办|拿主意就行|看着办就行|决定就行)"
    r"|(?:就|只)(?:咱俩|我们俩|你和我)(?:知道|说)"
    r"(?![^，。！？,.!?]{0,4}?(?:不用|不必|没关系))"
)

# ---- 引导私下 / 非正规渠道 ----
# 第一个分支要求"转账动作 + 我/个人/私人 + 渠道"三者同现，缺一不判：
#   "您可以转到我对公账户"  → 有转账有账户但没"我/个人"，不判
#   "用微信还是支付宝方便"  → 只有渠道名，没有转账动作，不判（这是正常的付款方式确认）
_PRIVATE_PATTERN = re.compile(
    r"(?:转|打|汇|付)(?:到|给|进|去|至)?"
    r"(?:我|您|你|他)?(?:的)?(?!对公)"
    r"(?![^，。！？,.!?]{0,6}?(?:公司|对公|企业|单位|账户名))"
    r"[^，。！？,.!?]{0,6}?"
    r"(?:微信|支付宝|账户|卡|这边)"
    # 第二分支原来是 "微信/支付宝 + 6 字内 + 转/打/付"，会把
    # "您这边是用微信还是支付宝方便？" 里的"付"字吃进去（支**付**宝），误判成私下交易。
    # 修法：渠道名后面必须跟真正的转账动作，且前面不能是"用/走/选/哪个/还是"这类选择句式。
    r"|(?<!用)(?<!走)(?<!选)(?<!是)(?:微信|支付宝)"
    r"(?:上|里|那边|这边)?"
    r"[^，。！？,.!?]{0,3}?(?:转给|转我|转过来|打我|打到|付给|付过来|收款|收一下)"
    r"|(?:点|扫|打开)(?:一下|下|开)?[^，。！？,.!?]{0,4}?(?:链接|码)"
    # 资金动作有两种写法：
    #   ① 动词就在后面："扫码付款就行"
    #   ② 动词在下一个分句开头："您扫一下这个码，转三千过来" —— 要看逗号之后的内容，
    #      所以前瞻是 [^。！？]（允许跨逗号）而不是 [^，。！？]，{0,20} 是必要的。
    r"(?=[^。！？]{0,20}?(?:付款|付钱|转账|转给|转我|转过来|汇款|打款|打钱|交钱"
    r"|收一下|付一下|扫给我|收款码"
    # 动词+金额："付3000""转三千""打五千"—— 金额直接跟在资金动词后面。
    r"|[付转打汇交]\s*[\d一二三四五六七八九十百千万]+))"
    # "扫码查许可证"是合规动作，"扫码交钱"才违规——差别全在扫码之后那一步，
    # 所以这里不改词表（把"扫*二维码"整条删掉会漏检），改成"扫码 + 资金动作"才算数。
    # "内部名额"之前用的连接是 0~6 转义字，没排除逗号，会跨句误命中；
    # 现在统一用 [^，。！？] 显式字符类，跨不过分句。
    r"|(?:内部|内幕)[^，。！？,.!?]{0,6}?(?:名额|额度|份额|消息|人才能|渠道)"
    # "名额是内部定的 / 这个额度是内部留的"：把"内部"放到修饰位，一样是私下承诺
    r"|(?:名额|额度|份额)[^，。！？,.!?]{0,4}?(?:是|都是)?内部[^，。！？,.!?]{0,4}?"
    # 加微信 + 钱：加微信本身不违规（发资料都用微信），落在"钱"上才是引导私下交易。
    # 判据：加微信 与 转账/付/打款/费用 同句出现，且中间不过句号。
    r"|(?:加|添加|扫)[^，。！？,.!?]{0,4}?(?:我|私人)[^，。！？,.!?]{0,2}?(?:微信|好友)"
    r"(?=[^。！？]{0,20}?(?:转账|转给|转我|付款|付给|打款|打钱|费用|交费|收款))"
)

# ---- 冒充官方背景 ----
# 除了"政府背景"这种正着说的，还有一种反着说的："我们背后是国资""我们股东是央企"。
# "背后是/股东是/出资方是 + 国资/央企/国有" 才是背书，单说"我们是国企"是事实陈述，
# 所以判据落在"背后/股东/出资"这类**借势词**上，而不是落在"国资"这个名词上。
_OFFICIAL_PATTERN = re.compile(
    r"(?:政府|部委|监管|国有|央企|国资|国家|官方)[^，。！？,.!?]{0,6}"
    r"(?:背景|合作|支持|背书|单位|机构|平台)"
    r"|(?:背后|背后是|股东|出资方|大股东|实控人|上级|上面|上面是)[^，。！？,.!?]{0,4}?"
    r"(?:是|为|都是)?[^，。！？,.!?]{0,4}?"
    r"(?:国资|央企|国有|政府|国家|财政|财政部|发改委|人民银行|银保监|证监|事业单)"
    r"|(?:国资|央企|国有|政府|国家)[^，。！？,.!?]{0,6}?(?:控股|全资|直属|参股)"
)


@dataclass
class StructuralHit:
    pattern: str        # 哪条结构规则
    category: str
    severity: str
    why: str
    text: str
    matched: str
    negated: bool = False
    context: str = ""
    count: int = 1

    @property
    def confirmed(self) -> bool:
        return not self.negated

    def to_dict(self) -> dict:
        return {
            "rule_id": f"struct:{self.pattern}",
            "category": self.category,
            "severity": self.severity,
            "why": self.why,
            "turn_index": -1, "t": 0.0, "role": "agent",
            "matched": self.matched,
            "negated": self.negated,
            "confirmed": self.confirmed,
            "context": self.context,
            "count": self.count,
            "text": self.text,
            "structural": True,
        }


_STRUCT_RULES: list[tuple[str, re.Pattern, str, str, str]] = [
    ("ask_secret", _ASK_PATTERN, "索取敏感信息", "block",
     "句式识别：要的动作 + 敏感情报载体（码/卡号/证件/数字），可能绕开了『验证码』这类词"),
    ("certain_return", _CERTAIN_PATTERN, "承诺收益 / 保本", "block",
     "句式识别：确定性表述（固定/写死/跑不了/一分不少），实质是承诺保本保收益"),
    ("threat", _THREAT_PATTERN, "威胁 / 施压", "block",
     "句式识别：条件 + 后果（不还…就上征信/走后门/上门），属施压话术"),
    ("isolate", _ISOLATE_PATTERN, "隔离家人", "block",
     "句式识别：劝阻客户告知家人/朋友，是电诈里切断外部意见的关键一步"),
    ("private", _PRIVATE_PATTERN, "引导私下交易", "block",
     "句式识别：引导脱离公司渠道（转我微信 / 点链接 / 内部名额）"),
    ("official", _OFFICIAL_PATTERN, "冒充官方 / 公检法", "block",
     "句式识别：借政府/国有/监管给自己背书"),
]

# 反诈提示的句式：坐席在**提醒**客户别给，不是在索要。
# "我们不会向您索要任何验证码或密码" —— 这句本身就是合规话术。
#
# 为什么单独处理：上面那条否定降级已经把它判成"疑似"了，不算误判。
# 但"疑似"要进人工复核队列，一通正常电话也进队列，质检员一天看几百条会直接放弃。
# **降级的代价是人工成本，所以降级不能滥用。**
# 判据很稳：说的是"我们不会…您"（保护对方）而不是"您把…给我"（索取）。
_PROTECT_RE = re.compile(
    r"(?:我们|这边|我)[^，。！？,.!?]{0,8}(?:不会|绝不|不会去|从不|从来没有|不需要)"
    r"[^，。！？,.!?]{0,14}(?:索要|要|问|索取|要求|让您|叫您)"
    r"|(?:谨防|警惕|小心|切勿|不要)[^，。！？,.!?]{0,6}(?:泄露|告诉|提供|给|透露)"
    # 否定式合规声明："不承诺收益""不保证保本""没有任何保本一说"
    # 这类句子是机构主动做的风险提示，是合规话术本身，不该进人工队列。
    r"|(?:不|绝不|从不|没有)(?:承诺|保证|宣称|说)"
    r"[^，。！？,.!?]{0,6}(?:收益|保本|保底|回报)"
)


@dataclass
class RedlineHit:
    rule_id: str
    category: str
    severity: str
    why: str
    turn_index: int
    t: float
    role: str
    text: str
    matched: str
    negated: bool = False
    context: str = ""
    count: int = 1          # 同一条规则在同一句话里命中的次数

    @property
    def confirmed(self) -> bool:
        """确认违规：命中且不在否定语境里。"""
        return not self.negated

    def to_dict(self) -> dict:
        return {
            "rule_id": self.rule_id,
            "category": self.category,
            "severity": self.severity,
            "why": self.why,
            "turn_index": self.turn_index,
            "t": self.t,
            "role": self.role,
            "matched": self.matched,
            "negated": self.negated,
            "confirmed": self.confirmed,
            "context": self.context,
            "count": self.count,
            "text": self.text,
        }


@dataclass
class ScanResult:
    hits: list[RedlineHit] = field(default_factory=list)
    struct_hits: list[StructuralHit] = field(default_factory=list)
    skipped_customer_mentions: int = 0  # 客户自己说的，跳过的次数（透明化用）

    @property
    def all_hits(self):
        return list(self.hits) + list(self.struct_hits)

    @property
    def confirmed_hits(self):
        return [h for h in self.all_hits if h.confirmed]

    @property
    def suspected_hits(self):
        return [h for h in self.all_hits if h.negated]

    @property
    def blocked(self) -> bool:
        return any(h.severity == "block" for h in self.confirmed_hits)

    def to_dict(self) -> dict:
        return {
            "confirmed_count": len(self.confirmed_hits),
            "suspected_count": len(self.suspected_hits),
            "skipped_customer_mentions": self.skipped_customer_mentions,
            "blocked": self.blocked,
            "hits": [h.to_dict() for h in self.all_hits],
        }


def _is_negated(text: str, start: int) -> bool:
    """看匹配点前面 NEG_WINDOW 个字里有没有否定词。

    有一个细节：否定词要**就近**判断。"我不认为这个产品没有风险"这种双重否定，
    简单看前面 8 个字会判成否定，其实是否定之否定。
    处理办法是取**离匹配点最近**的那个否定词，如果它和匹配点之间还夹着
    另一个否定结构，就认为是双重否定，判回"确认违规"。

    这一条是真实场景踩出来的：金融坐席很爱说"不能说完全没有风险"，
    这句话的本质仍然是在暗示没风险，简单降级会放过去。

    还有一个更隐蔽的坑：**否定会跨句漂移**。
        "不还的话我们发律师函，到时候更麻烦"
    这里"不"属于前半句的条件（"不还的话"），跟后面的"律师函"没有否定关系，
    但纯按距离算，它在 8 个字以内，于是"律师函"被降级成疑似，威胁就被放过了。

    修法：否定词和匹配点之间如果有句读、或者有"的话/就/之后"这类条件/让步连接，
    就认为否定只在它自己那个分句里，不外溢。
    """
    left = text[max(0, start - NEG_WINDOW): start]
    positions = [(left.rfind(n), n) for n in NEGATIONS if n in left]
    if not positions:
        return False
    nearest_pos, _ = max(positions)

    # 否定不外溢：分句已经结束（有句读），或中间出现条件/让步连接
    between_raw = left[nearest_pos:]
    if any(ch in between_raw for ch in "，。！？；,.!?;"):
        return False
    if any(w in between_raw for w in ["的话", "之后就", "以后就", "要不", "否则"]):
        return False

    # 最近否定词到匹配点之间，如果还出现否定词，说明是否定之否定
    extra = [n for n in NEGATIONS if n in between_raw and between_raw.find(n) > 0]
    if extra:
        return False
    return True


def _snippet(text: str, start: int, end: int, pad: int = 10) -> str:
    left = max(0, start - pad)
    right = min(len(text), end + pad)
    s = text[left:right]
    return ("…" if left > 0 else "") + s + ("…" if right < len(text) else "")


# 提前编译，避免每次扫描重复编译几百条正则
_PATTERNS: dict[str, re.Pattern] = {
    w: _compile(w) for rule in RULES for w in rule["words"]
}


# 结构规则 → 词表规则 的对应关系。
# 结构层只负责"词表没抓到的那部分"，同一语义方向已经有词表命中时就不重复报，
# 否则一通电话会因为同一句话被扣两次分。
_STRUCT_TO_WORD = {
    "ask_secret": "sensitive_info",
    "certain_return": "guarantee_return",
    "threat": "coercion",
    "isolate": "private_deal",
    "private": "private_deal",
    "official": "impersonate",
}


def _struct_covered_by_words(struct_name: str, word_rule_ids: set[str]) -> bool:
    mapped = _STRUCT_TO_WORD.get(struct_name)
    return mapped is not None and mapped in word_rule_ids


def _scan_structural(text: str) -> list[tuple[str, str, str, str, str, int, int]]:
    """跑结构规则层。返回 (pattern, category, severity, why, matched, start, end)。

    结构层和词表层的分工：
      词表 —— 高频硬词，准确率优先
      结构 —— 句式改写，召回优先
    两层都命中时由 scan() 去重（结构层命中不加倍计数）。
    """
    out = []
    for name, pat, category, severity, why in _STRUCT_RULES:
        for m in pat.finditer(text):
            out.append((name, category, severity, why, m.group(0), m.start(), m.end()))
    return out


def scan(transcript: dict) -> ScanResult:
    """扫一通电话。只扫坐席说的话。

    同一句里可能多个词重叠命中（"稳赚不赔"里同时有"稳赚"），
    所以先收集所有 (start, end, word)，合并重叠区间只留最长的那个。
    不去重的话，一句话会被算成两三处违规，扣分量级就失真了。

    跑两层：词表层 + 结构层。同一句里两层都命中时，只保留词表层
    （它更准、更能解释），结构层只补词表抓不到的那些。
    """
    result = ScanResult()
    turns = transcript.get("turns", [])

    for idx, turn in enumerate(turns):
        role = turn.get("role", "")
        text = turn.get("text", "") or ""
        if not text:
            continue

        # ---- 结构层 ----
        if role == "agent":
            struct_spans = _scan_structural(text)
            word_rule_ids = set()
            for rule in RULES:
                for word in rule["words"]:
                    pat = _PATTERNS.get(word) or _compile(word)
                    if pat.search(text):
                        word_rule_ids.add(rule["id"])
            seen_struct: set[str] = set()
            for name, category, severity, why, matched, s, e in struct_spans:
                if name in seen_struct:
                    continue
                # 词表已经抓到了同一个语义方向，就不重复报
                if _struct_covered_by_words(name, word_rule_ids):
                    continue
                seen_struct.add(name)
                result.struct_hits.append(StructuralHit(
                    pattern=name, category=category, severity=severity, why=why,
                    text=text, matched=matched,
                    negated=_is_negated(text, s),
                    context=_snippet(text, s, e),
                ))
        elif role != "agent":
            # 客户说的话也要计数，报告里要能解释"为什么提到敏感内容却没判违规"
            for rule in RULES:
                for word in rule["words"]:
                    pat = _PATTERNS.get(word) or _compile(word)
                    result.skipped_customer_mentions += len(pat.findall(text))

        for rule in RULES:
            spans: list[tuple[int, int, str]] = []
            for word in rule["words"]:
                pat = _PATTERNS.get(word) or _compile(word)
                for m in pat.finditer(text):
                    if role != "agent":
                        # 客户说的不算违规，但记一下，报告里要能解释
                        # "为什么这通电话提到了保本却没判违规"
                        result.skipped_customer_mentions += 1
                        continue
                    spans.append((m.start(), m.end(), word))

            if not spans:
                continue

            # 按起点排序，重叠的合并，保留最长匹配
            spans.sort(key=lambda s: (s[0], -(s[1] - s[0])))
            kept: list[tuple[int, int, str]] = []
            for s, e, w in spans:
                if kept and s < kept[-1][1]:
                    # 和前一个重叠：留下更长的
                    ps, pe, pw = kept[-1]
                    if (e - s) > (pe - ps):
                        kept[-1] = (s, e, w)
                    continue
                kept.append((s, e, w))

            for s, e, w in kept:
                # 同一条规则在同一句话里出现两次（比如"验证码"说了两遍），
                # 合成一条、只记次数。分成两条会让报告看起来比实际更严重。
                same = next((h for h in result.hits
                             if h.rule_id == rule["id"] and h.turn_index == idx), None)
                if same is not None:
                    same.count += 1
                    continue
                negated = _is_negated(text, s)
                # 反诈提示句直接放掉，不进"疑似"队列（见 _PROTECT_RE 的注释）。
                # 注意这里判的是**整句**，不是命中点附近——
                # "我们不会向您索要验证码或密码"里，"密码"离"不会"有 10 个字，
                # 超出 NEG_WINDOW，逐点判会被判成确认违规。但整句的意图是明确的。
                if _PROTECT_RE.search(text):
                    continue
                if negated and _PROTECT_RE.search(text):
                    continue
                result.hits.append(
                    RedlineHit(
                        rule_id=rule["id"],
                        category=rule["category"],
                        severity=rule["severity"],
                        why=rule["why"],
                        turn_index=idx,
                        t=turn.get("t", 0.0),
                        role=role,
                        text=text,
                        matched=w,
                        negated=negated,
                        context=_snippet(text, s, e),
                    )
                )
    return result


