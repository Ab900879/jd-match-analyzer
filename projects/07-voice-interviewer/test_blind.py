# 已知会失败的条目：不是忘了修，是修不好的——记在这里，让数字诚实。
# 每条都要写清"为什么现在这套判据做不到"。
KNOWN_LIMITS = {
    "我不太喜欢做那种做完就扔的东西。做 AI 产品能看到它被人天天用，被骂也好，这个反馈对我很重要。":
        "价值判断型动机（我不喜欢X，因为Y）。既没有数字、没有动作，也没有类比——"
        "它表达的是取向，不是经历，而锚点体系里没有「取向」这个类别。",

    "通信做的是把信号从这头传到那头，我觉得 AI 产品做的是把意思从人这头传到那头，是一类问题。":
        "平行对照句式（A 做的是X，B 做的是Y，是一类问题）。语义上是最漂亮的类比，"
        "但字面没有「像/一样/一回事/同理」任何一个词，正则抓不到这种「结构对仗」的相似。",

    "现在质检报告出来得太慢，隔天才看得到，我想改成当天就出，第二天早会直接拿来看。":
        "提议型答案，讲清了「哪里不好 + 改成什么」，但两组要点词都没命中："
        "缺「电话/外呼/坐席」这类行业词，「隔天/当天/早会」也不在词表里。"
        "这类题的正确判法应该是「时间维度上的改动」，跟词表无关——但现在的判据做不到。",
}


def run() -> int:
    qs = {q["id"]: q for q in core.load_questions()}
    total_ok = total = 0
    print("=" * 66)
    for name, tuned, cases in BATCHES:
        ok = 0
        bad = []
        for qid, should, answer in cases:
            v = core.judge(answer, qs[qid])
            if v.passed == should:
                ok += 1
            else:
                bad.append((qid, should, answer, v.failed_rules))
        total_ok += ok
        total += len(cases)
        tag = "（调过，只能算没退化）" if tuned else ""
        print(f"{name}{tag}: {ok}/{len(cases)}")
        for qid, should, answer, rules in bad:
            if answer in KNOWN_LIMITS:
                print(f"   [已知边界] {qid} {KNOWN_LIMITS[answer]}")
            else:
                kind = "误杀好答案" if should else "放过烂答案"
                print(f"   [新问题·{kind}] {qid} {rules}｜{answer[:40]}…")
    print("=" * 66)
    print(f"合计 {total_ok}/{total}（{total_ok/total:.1%}）")
    print(f"其中未调过的终验批（5/6/14 批）单独看：见 README 的数据表")
    return 0


if __name__ == "__main__":
    sys.exit(run())
