# 结构规则层：不看具体词，看"句式 + 要素"
#
# 为什么要有这一层：词表是一条追不上的路。
#   补了"验证码"，坐席说"那个码"；补了"卡号"，说"卡上那串"；
#   补了"告诉家人"，说"别让家里知道"；补了"起诉"，说"征信上就有记录"。
# 每一批新数据都会冒出新的说法，手工补词永远落后一步。
#
# 但**句式的种类是有限的**。坐席能说的话，在这些模式里打转：
#   索要：把 <X> 给我 / 念一下 / 报一下 / 填一下
#   承诺：固定 / 写死 / 稳 / 跑不了 / 一分不少
#   威胁：不 <做某事> 就 <后果> / 会影响 <征信/记录>
#   隔离：别让 <某类人> 知道 / 别跟 <某类人> 商量
#   私下：转我 <渠道> / 扫 <码> / 点 <链接>
# 所以这一层是"模式识别"，跟词表互为补充：
#   词表管高频硬词（准），结构层管改写（召回），两层都命中就升级为违规。
