# 把词条编译成正则。词条有两种写法，编译方式不同：
#
#   纯字面词（"保本"）→ 每个字之间允许夹 0~2 个标点/空白
#                      这样"保…本"、"保，本"都能抓到，但语义不变
#
#   带量词的词（"无*风险"）→ {0,3} 表示"中间可以插 0~3 个任意字"，
#                      用来覆盖"没有任何风险"这种插入语
#
# 第一版把两者混在一条规则里，结果"无*风险"编成了
# "无[标点]{0,2}{0,3}风…"——两个量词叠在一起是非法正则，直接报 multiple repeat。
# 分开处理之后就不会互相污染了。
_PUNCT_GAP = r"[\s，。！？、,.!?；;：:“”\"'‘’（）()…—-]{0,2}"

# 词条编译后逐字之间的"标点空隙"，额外排除否定词。
# 为什么需要：词表是**不分句**匹配的，"寄到*家里"如果不排除逗号，
#   会被 "您要不要先跟家里人商量一下" 这句里 "不要…家里" 跨过逗号命中（"不要"是否定，"不要先跟"不是）。
#   加了分句边界之后，"不要…，…家里"就跨不过去了。
# 反之结构层用的是显式 [^，。！？] 字符类，没有这个问题。
_WORD_GAP = (
    r"(?:[\s，。！？、,.!?；;：:“”\"'‘’（）()…—-]{0,2}"
    r"(?![不要没无非]|不会|绝不|不存在))"
)

# 同义字组：写进词条时用 [无|没|零|没有] 这种写法表示"这几个说法都算"。
# 为什么需要这个：本来以为"无风险"加个空隙就能覆盖"没有任何风险"，
# 结果发现"没有任何风险"里**根本没有"无"字**——它是"没"+"有"。
# 所以这不是空隙问题，是同义替换问题，得单独一层。
#
# 只对**少数几个**高频否定词做同义展开（无/没/零），不做通用同义词库。
# 因为通用同义词库会引入不可控的误判，而规则层要的是可解释：
# 出错的时候必须能一眼看出是哪个词条命中的。
_ALT = {
    "无": "无|没|没有|零|毫无|绝无",
    "没": "没|没有|无",
    "零": "零|无",
}


def _compile(word: str) -> re.Pattern:
    """把词条编成正则。语法只有三条，故意做得很少，多了维护的人记不住：

        *              这里可以有 0~4 个任意字（跳过插入语）
        [无]           这里可以是"无/没/没有/零/毫无/绝无"里的任意一个
        其他字          逐字匹配，字与字之间允许夹标点和空格

    "无*风险"   → 命中 无风险 / 没有任何风险 / 完全没有风险 / 零风险
    "银行*工作人员" → 命中 银行工作人员 / 银行的工作人员

    注意：逐字之间的空隙用的是 _WORD_GAP（排除否定词的标点空隙），
    不是裸的标点类。原因见 _WORD_GAP 的注释——词表不分句，跨逗号会踩到下一句的否定词。
    """
    out: list[str] = []
    for i, ch in enumerate(word):
        nxt = word[i + 1] if i + 1 < len(word) else ""
        if ch == "*":
            if out and out[-1] == _WORD_GAP:
                out.pop()
            out.append(r".{0,4}")
            continue
        if ch in _ALT:
            if out and out[-1] == _WORD_GAP:
                out.pop()
            out.append(f"(?:{_ALT[ch]})")
            if nxt and nxt not in "*":
                out.append(_WORD_GAP)
            continue
        out.append(re.escape(ch))
        if nxt and nxt not in "*":
            out.append(_WORD_GAP)
    return re.compile("".join(out))

